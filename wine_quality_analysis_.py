cluster_features = [
    "fixed acidity",
    "volatile acidity",
    "citric acid",
    "residual sugar",
    "chlorides",
    "free sulfur dioxide",
    "total sulfur dioxide",
    "density",
    "pH",
    "sulphates",
    "alcohol"
]

X_cluster = df[cluster_features].copy()

print("Clustering data shape:", X_cluster.shape)
display(X_cluster.head())

from sklearn.preprocessing import StandardScaler

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X_cluster)

print("Scaled data shape:", X_scaled.shape)
print("Feature means:", np.round(X_scaled.mean(axis=0), 3))
print("Feature standard deviations:",
      np.round(X_scaled.std(axis=0), 3))

from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

k_values = range(2, 9)
inertias = []
silhouette_scores = []

for k in k_values:
    kmeans = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    labels = kmeans.fit_predict(X_scaled)

    inertias.append(kmeans.inertia_)

    score = silhouette_score(
        X_scaled,
        labels,
        sample_size=min(2000, len(X_scaled)),
        random_state=42
    )

    silhouette_scores.append(score)

    print(f"K={k} | Inertia={kmeans.inertia_:.2f} "
          f"| Silhouette={score:.4f}")

fig, axes = plt.subplots(1, 2, figsize=(13, 5))

axes[0].plot(
    list(k_values),
    inertias,
    marker="o"
)
axes[0].set_title("Elbow Method")
axes[0].set_xlabel("Number of Clusters (K)")
axes[0].set_ylabel("Inertia")

axes[1].plot(
    list(k_values),
    silhouette_scores,
    marker="o"
)
axes[1].set_title("Silhouette Score")
axes[1].set_xlabel("Number of Clusters (K)")
axes[1].set_ylabel("Silhouette Score")

plt.tight_layout()
plt.show()

best_k = list(k_values)[np.argmax(silhouette_scores)]

print("Selected number of clusters:", best_k)

final_kmeans = KMeans(
    n_clusters=best_k,
    random_state=42,
    n_init=10
)

df["cluster"] = final_kmeans.fit_predict(X_scaled)

