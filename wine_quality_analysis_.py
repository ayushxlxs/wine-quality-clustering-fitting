# Use chemical measurements to predict quality
X = df[cluster_features].copy()
y = df["quality"].copy()

# Split data before fitting the scaler to prevent data leakage
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

# Standardise using training data only
reg_scaler = StandardScaler()

X_train_scaled = reg_scaler.fit_transform(X_train)
X_test_scaled = reg_scaler.transform(X_test)

print("Training observations:", X_train.shape[0])
print("Testing observations:", X_test.shape[0])
print("Number of input features:", X_train.shape[1])

from sklearn.linear_model import LinearRegression

# Create and train the model
regression_model = LinearRegression()
regression_model.fit(X_train_scaled, y_train)

# Generate predictions for unseen test data
y_pred = regression_model.predict(X_test_scaled)

print("Regression model trained successfully.")
print("First 10 actual quality scores:")
print(y_test.iloc[:10].to_list())

print("\nFirst 10 predicted quality scores:")
print(np.round(y_pred[:10], 2))

from sklearn.metrics import mean_squared_error, r2_score

rmse = np.sqrt(mean_squared_error(y_test, y_pred))
r2 = r2_score(y_test, y_pred)

print("REGRESSION MODEL EVALUATION")
